"""Builds the code-drawn pixel art (npm run art): the sheets in public/art/wizards/, circle/ and
spells/, their entries in public/art/manifest.json and data/wizard-art.json. Then runs the check.
Deterministic: the same code always writes the same files.

Wizard sheets: one per layer, one row per animation (idle, hurt, victory, then the casts), one column
per frame, each frame 48x64 art pixels, drawn facing right. Circle sheets: one per tier and layer,
one row per variant, one column per frame. Spell sheets: one per spell, row 0 the flight and row 1
the impact (the ward has one row).
"""
import json
import sys
from pathlib import Path

import circle as cc
import convert
import scroll
from check import problems
from palette import KEY, SEATS, SPARK_RAMPS
from pix import H, W, area, sheet
import spells as sp
import wizards as wz

ROOT = Path(__file__).resolve().parents[2]
ART = ROOT / "public" / "art"
DATA = ROOT / "data" / "wizard-art.json"
MANIFEST = ART / "manifest.json"
SCALE = 3
ORDER = ["robe", "body", "hat", "staff", "hands"]  # drawing order, back to front


def save(path, rows_of_frames):
    """Writes one sheet (the frames are the size of pix.AREA) and returns its path in public/art/."""
    (ART / path).parent.mkdir(parents=True, exist_ok=True)
    sheet(rows_of_frames, max(len(r) for r in rows_of_frames)).save(ART / path, optimize=False)
    return path


def build_wizards():
    area(W, H)
    rows = wz.all_frames()
    layers = {"body": wz.body_layer, "hands": wz.hands_layer, "staff": wz.staff_layer}
    layers.update({f"robe_{i}": (lambda p, k=i: wz.robe_layer(p, k)) for i, _ in wz.ROBES})
    layers.update({f"hat_{i}": (lambda p, k=i: wz.hat_layer(p, k)) for i, _ in wz.HATS})
    files = [save(f"wizards/{name}.png", [[fn(p) for p in a["frames"]] for _, a in rows]) for name, fn in layers.items()]

    def anim(row, a):
        pts = [{"tip": [round(v) for v in wz.staff_tip(p)], "feet": [24, 63]} for p in a["frames"]]
        out = {"row": row, "frames": len(a["frames"]), "ms": a["ms"], "loop": a["loop"]}
        if "release" in a:
            out["release"] = a["release"]
        out["points"] = pts
        return out

    by_row = {name: i for i, (name, _) in enumerate(rows)}
    data = {
        "_comment": "Generated by tools/art/build.py (npm run art) from tools/art/. Don't edit by hand: change the generator and re-run it. "
                    "Sheets are in public/art/: one row per animation (row), one column per frame, each frame.w x frame.h art pixels, "
                    "drawn facing right, shown at scale screen pixels per art pixel. Robe and hat sheets are drawn in keyRamp: swap "
                    "keyRamp[i] for a colour's ramp[i] (ramp[2] is the seat colour the interface uses). Layers draw in layerOrder, back to "
                    "front. Points are art pixels in the frame: tip is the staff's gem (where a spell glow sits), feet where the wizard stands. "
                    "release is the frame a cast lets the spell go. circle: one sheet per tier and layer, one row per variant (variant v of "
                    "every tier is one design, so fade tiers within a variant), all looping; centre and radius place it; the beam's anchor "
                    "sits on the circle's centre. spells: drawn flying right, in the spark's colours; head is the flight's leading point and "
                    "impacts are centred in their frame. ward and finalSpell are drawn in keyRamp: the ward takes each spark's ramp, and "
                    "the game scales and tints the final spell by tier. scroll: the map's parchment, plain paper; mapArea is [x, y, w, h], "
                    "where the game draws the map on it.",
        "scale": SCALE,
        "frame": {"w": W, "h": H},
        "keyRamp": KEY,
        "colours": [{"id": i, "name": n, "ramp": r} for i, n, r in SEATS],
        "layerOrder": ORDER,
        "sheets": {"body": "wizards/body.png", "staff": "wizards/staff.png", "hands": "wizards/hands.png"},
        "hats": [{"id": i, "name": n, "sheet": f"wizards/hat_{i}.png"} for i, n in wz.HATS],
        "robes": [{"id": i, "name": n, "sheet": f"wizards/robe_{i}.png"} for i, n in wz.ROBES],
        "animations": {
            "idle": anim(by_row["idle"], wz.ANIMATIONS["idle"]),
            "hurt": anim(by_row["hurt"], wz.ANIMATIONS["hurt"]),
            "victory": anim(by_row["victory"], wz.ANIMATIONS["victory"]),
            "casts": [dict(id=c["id"], **anim(by_row["cast_" + c["id"]], c)) for c in wz.ANIMATIONS["casts"]],
        },
    }
    return data, files


def build_circle():
    files, tiers = [], []
    area(cc.FW, cc.FH)
    for t, layers in enumerate(cc.TIERS):
        out = []
        for layer in layers:
            path = save(f"circle/tier{t}_{layer}.png",
                        [[cc.LAYERS[layer](t, v, f) for f in range(cc.FRAMES)] for v in range(len(cc.FIGURES))])
            files.append(path)
            out.append({"id": layer, "sheet": path})
        tiers.append({"tier": t, "ms": [cc.MS[t]] * cc.FRAMES, "layers": out})
    area(cc.BEAM["w"], cc.BEAM["h"])
    files.append(save("circle/beam.png", [[cc.beam(f) for f in range(cc.FRAMES)]]))
    data = {
        "frame": {"w": cc.FW, "h": cc.FH}, "centre": [cc.CX, cc.CY], "radius": [cc.RX, cc.RY],
        "variants": len(cc.FIGURES), "frames": cc.FRAMES, "loop": True, "tiers": tiers,
        "beam": {"sheet": "circle/beam.png", "frame": {"w": cc.BEAM["w"], "h": cc.BEAM["h"]},
                 "anchor": [cc.BEAM["w"] // 2, cc.BEAM["h"] - 1], "frames": cc.FRAMES, "ms": [cc.BEAM["ms"]] * cc.FRAMES, "loop": True},
    }
    return data, files


def build_spells():
    files, spells = [], []
    for spell_id, spark, name in sp.DAMAGE:
        path = save(f"spells/{spell_id}.png", sp.damage_frames(spell_id, spark))
        files.append(path)
        spells.append({"id": spell_id, "spark": spark, "name": name, "sheet": path,
                       "frame": {"w": sp.SPELL["w"], "h": sp.SPELL["h"]}, "head": list(sp.SPELL["head"]),
                       "flight": {"row": 0, "frames": len(sp.FLIGHT_MS), "ms": sp.FLIGHT_MS, "loop": True},
                       "impact": {"row": 1, "frames": len(sp.IMPACT_MS), "ms": sp.IMPACT_MS, "loop": False}})
    frames = [sp.ward(f) for f in range(len(sp.WARD_MS))]
    files.append(save("spells/ward.png", [frames]))
    ward = {"sheet": "spells/ward.png", "frame": {"w": sp.WARD["w"], "h": sp.WARD["h"]}, "frames": len(sp.WARD_MS),
            "ms": sp.WARD_MS, "loop": False,
            "colours": [{"spark": k, "name": f"{k} ward", "ramp": r} for k, r in SPARK_RAMPS.items()]}
    rows = [[sp.final_flight(f) for f in range(len(sp.FINAL_FLIGHT_MS))], [sp.final_impact(f) for f in range(len(sp.FINAL_IMPACT_MS))]]
    files.append(save("spells/final.png", rows))
    final = {"sheet": "spells/final.png", "frame": {"w": sp.FINAL["w"], "h": sp.FINAL["h"]}, "head": list(sp.FINAL["head"]),
             "flight": {"row": 0, "frames": len(sp.FINAL_FLIGHT_MS), "ms": sp.FINAL_FLIGHT_MS, "loop": True},
             "impact": {"row": 1, "frames": len(sp.FINAL_IMPACT_MS), "ms": sp.FINAL_IMPACT_MS, "loop": False}}
    return spells, ward, final, files


def update_manifest(files):
    listed = json.loads(MANIFEST.read_text())
    keep = [f for f in listed if not f.startswith(("wizards/", "circle/", "spells/", "enemies/", "backgrounds/", "map/", "ui/", "charms/"))]
    MANIFEST.write_text(json.dumps(keep + sorted(files), indent=2) + "\n", newline="\n")


if __name__ == "__main__":
    data, files = build_wizards()
    data["circle"], more = build_circle()
    files += more
    data["spells"], data["ward"], data["finalSpell"], more = build_spells()
    files += more
    files += convert.convert_all()
    scroll.draw().save(ART / "map/scroll.png", optimize=False)
    files.append("map/scroll.png")
    w, h = scroll.size()
    data["scroll"] = {"sheet": "map/scroll.png", "w": w, "h": h, "mapArea": scroll.map_area()}
    DATA.write_text(json.dumps(data, indent=2) + "\n", newline="\n")
    update_manifest(files)
    print(f"wrote {len(files)} files, data/wizard-art.json, data/enemy-art.json and the manifest")
    found = problems()
    for p in found:
        print("FAIL", p)
    print("art check:", "failed" if found else "passed")
    sys.exit(1 if found else 0)
